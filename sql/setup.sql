USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS RETAIL_ML;
CREATE SCHEMA IF NOT EXISTS RETAIL_ML.ANALYTICS;

CREATE OR REPLACE WAREHOUSE RETAIL_ML_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE TABLE RETAIL_ML.ANALYTICS.SALES_RAW (
    SALE_DATE DATE,
    REVENUE NUMBER(18, 2),
    QUANTITY NUMBER(18, 0)
);

